"""Build the PHP SDK from spec/openapi.json (Python 3 standard library only).

Writes files that are never edited by hand:
  src/Types.php        a PHPStan array shape for every request and response
  src/Resources/*.php  $client->emails->send() and the other methods, named
                       from the x-sdk-group and x-sdk-method of each operation
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = json.loads((ROOT / "spec/openapi.json").read_text())
SCHEMAS = SPEC["components"]["schemas"]
METHODS = ["get", "post", "put", "patch", "delete"]
HEADER = "<?php\n\n// Generated by scripts/generate.py from spec/openapi.json. Do not edit.\n\ndeclare(strict_types=1);\n\n"
# Query parameters a ...All method leaves out: it walks forward by `after` itself.
PAGINATION_MANAGED = ("page", "before", "latest")


def pascal(s):
    return "".join(p[:1].upper() + p[1:] for p in re.split(r"[^A-Za-z0-9]+", s) if p)


def camel(s):
    p = pascal(s)
    return p[:1].lower() + p[1:]


def deref(schema):
    while isinstance(schema, dict) and "$ref" in schema:
        schema = SCHEMAS[schema["$ref"].split("/")[-1]]
    return schema


def ref_name(schema):
    return pascal(schema["$ref"].split("/")[-1])


def doc(text):
    """One line of text that is safe inside a PHP doc comment."""
    line = (text or "").strip().splitlines()[0] if (text or "").strip() else ""
    return line.replace("*/", "*\\/")[:150]


def literal(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return json.dumps(value)
    return "'" + str(value).replace("\\", "\\\\").replace("'", "\\'").replace("*/", "*\\/") + "'"


def union(members):
    seen = []
    for m in members:
        for part in split_union(m):
            if part not in seen:
                seen.append(part)
    if "mixed" in seen:
        return "mixed"
    # null last, as PHP prints it
    return "|".join([p for p in seen if p != "null"] + (["null"] if "null" in seen else []))


def split_union(t):
    parts, depth, cur = [], 0, ""
    quoted = False
    for i, ch in enumerate(t):
        if ch == "'" and (i == 0 or t[i - 1] != "\\"):
            quoted = not quoted
        if not quoted:
            if ch in "<{(":
                depth += 1
            elif ch in ">})":
                depth -= 1
            elif ch == "|" and depth == 0:
                parts.append(cur)
                cur = ""
                continue
        cur += ch
    parts.append(cur)
    return parts


# --- Types.php -----------------------------------------------------------------

def expr(schema):
    """The PHPStan type for a schema. Component schemas are referenced by alias name."""
    if schema is None or schema is True or schema == {}:
        return "mixed"
    if "$ref" in schema:
        return ref_name(schema)
    for key in ("anyOf", "oneOf"):
        if key in schema:
            return union([expr(s) for s in schema[key]])
    if "allOf" in schema:
        if len(schema["allOf"]) == 1 and not schema.get("properties"):
            return expr(schema["allOf"][0])
        return shape(merge_all_of(schema))
    types = schema.get("type")
    types = types if isinstance(types, list) else [types] if types else []
    nullable = "null" in types
    types = [t for t in types if t != "null"]
    if "enum" in schema:
        values = [v for v in schema["enum"] if v is not None]
        nullable = nullable or None in schema["enum"]
        out = union([literal(v) for v in values]) if values else "null"
    elif len(types) > 1:
        out = union([expr({**schema, "type": t}) for t in types])
    elif not types:
        if nullable and not any(k in schema for k in ("properties", "items", "additionalProperties")):
            return "null"
        out = shape(schema) if "properties" in schema else "mixed"
    else:
        t = types[0]
        if t == "string":
            out = "string"
        elif t == "integer":
            out = "int"
        elif t == "number":
            out = "int|float"  # a JSON number without a fraction decodes to int
        elif t == "boolean":
            out = "bool"
        elif t == "array":
            out = f"list<{expr(schema.get('items'))}>"
        else:
            out = shape(schema)
    return union([out, "null"]) if nullable else out


def merge_all_of(schema):
    merged = {"type": "object", "properties": {}, "required": []}
    for part in schema["allOf"] + [schema]:
        part = deref(part)
        if "allOf" in part and part is not schema:
            part = merge_all_of(part)
        merged["properties"].update(part.get("properties", {}))
        merged["required"] += part.get("required", [])
    return merged


def shape(schema):
    props = schema.get("properties")
    if not props:
        extra = schema.get("additionalProperties")
        return f"array<string, {expr(extra) if isinstance(extra, dict) else 'mixed'}>"
    required = set(schema.get("required", []))
    fields = [f"{literal(k)}{'' if k in required else '?'}: {expr(p)}" for k, p in props.items()]
    return "array{" + ", ".join(fields) + "}"


aliases = {}  # name -> (type, description)
for name, schema in SCHEMAS.items():
    target = merge_all_of(schema) if "allOf" in schema else schema
    aliases[pascal(name)] = (expr(target), schema.get("description"))


def alias(name, schema, description=None):
    """A named type for an operation's inline request or response schema."""
    if "$ref" in schema:
        return ref_name(schema)
    if name in aliases:
        raise SystemExit(f"type name {name} is taken")
    aliases[name] = (expr(schema), description or schema.get("description"))
    return name


# --- operations ----------------------------------------------------------------

def native(schema):
    """The native PHP type of a query parameter, without null."""
    s = deref(schema or {})
    types = s.get("type")
    types = [t for t in (types if isinstance(types, list) else [types]) if t and t != "null"]
    if "enum" in s and not types:
        kinds = {type(v).__name__ for v in s["enum"] if v is not None}
        types = ["string" if kinds == {"str"} else "integer" if kinds == {"int"} else "mixed"]
    if len(types) != 1:
        return "mixed"
    return {"string": "string", "integer": "int", "number": "int|float", "boolean": "bool", "array": "array"}.get(types[0], "mixed")


ops = []
for path, item in SPEC["paths"].items():
    for method in METHODS:
        op = item.get(method)
        if not op:
            continue
        if "x-sdk-group" not in op or "x-sdk-method" not in op:
            raise SystemExit(f"{op['operationId']} has no x-sdk-group/x-sdk-method")
        name = pascal(op["operationId"])
        params = op.get("parameters", [])
        body_schema = (op.get("requestBody") or {}).get("content", {}).get("application/json", {}).get("schema")
        body = None
        if body_schema is not None:
            body = alias(name + "Params", body_schema)
        result = None
        for code, res in op.get("responses", {}).items():
            if code.startswith("2"):
                schema = (res.get("content") or {}).get("application/json", {}).get("schema")
                if schema is not None:
                    result = alias(name + "Response", schema)
                break
        path_params = re.findall(r"\{(\w+)\}", path)
        query = []
        for p in params:
            if p["in"] != "query":
                continue
            schema = p.get("schema") or {}
            fmt_json = (
                p["name"] == "format" and "json" in schema.get("enum", []) and schema.get("default") != "json"
            )
            query.append({
                "name": p["name"],
                "var": camel(p["name"]),
                "native": native(schema),
                "doc": expr(schema),
                "required": bool(p.get("required")),
                # The typed method decodes JSON, so it asks for JSON when the default format is something else.
                "json_format": fmt_json,
            })
        names = [camel(p) for p in path_params] + [q["var"] for q in query]
        if len(set(names)) != len(names) or set(names) & {"params", "options", "idempotencyKey"}:
            raise SystemExit(f"{op['operationId']}: parameter names collide: {names}")
        item_type = None
        if method == "get" and any(q["name"] == "after" for q in query):
            schema = deref(result and (op["responses"][next(c for c in op["responses"] if c.startswith("2"))]
                                       ["content"]["application/json"]["schema"]) or {})
            data = deref((schema.get("properties") or {}).get("data") or {})
            if data.get("type") == "array" and "has_more" in (schema.get("properties") or {}):
                items = data.get("items") or {}
                item_type = ref_name(items) if "$ref" in items else expr(items)
        ops.append({
            "group": op["x-sdk-group"],
            "method": op["x-sdk-method"],
            "http": method.upper(),
            "path": path,
            "summary": doc(op.get("summary") or op["operationId"]).rstrip("."),
            "path_params": path_params,
            "query": query,
            "body": body,
            "body_required": bool((op.get("requestBody") or {}).get("required")),
            "list_body": body_schema is not None and deref(body_schema).get("type") == "array",
            "result": result,
            "item": item_type,
            "idempotent": any(p["in"] == "header" and p["name"].lower() == "idempotency-key" for p in params),
        })


# --- Resources/*.php -------------------------------------------------------------

def class_name(prefix):
    return "".join(pascal(p) for p in prefix) + "Resource" if prefix else "ClientResources"


def signature(op, paged=False):
    """The PHP parameter list. Optional parameters come after required ones."""
    args = [f"string ${camel(p)}" for p in op["path_params"]]
    if op["body"] and op["body_required"] and not paged:
        args.append("array $params")
    for q in op["query"]:
        if q["required"]:
            args.append(f"{q['native']} ${q['var']}")
    if op["body"] and not op["body_required"] and not paged:
        args.append("?array $params = null")
    for q in op["query"]:
        if q["required"] or (paged and q["name"] in PAGINATION_MANAGED):
            continue
        t = q["native"]
        t = t if t == "mixed" else f"{t}|null" if "|" in t else f"?{t}"
        args.append(f"{t} ${q['var']} = null")
    if op["idempotent"] and not paged:
        args.append("?string $idempotencyKey = null")
    args.append("array $options = []")
    return ", ".join(args)


def docblock(op, paged=False):
    lines = []
    if paged:
        lines.append(f"Every item of {op['method']}(), fetching the following pages as you iterate. `GET {op['path']}`")
    else:
        lines.append(f"{op['summary']}. `{op['http']} {op['path']}`")
    lines.append("")
    if op["body"] and not paged:
        lines.append(f"@param {op['body'] if op['body_required'] else op['body'] + '|null'} $params")
    for q in op["query"]:
        if paged and q["name"] in PAGINATION_MANAGED:
            continue
        t = q["doc"] if q["required"] else union([q["doc"], "null"])
        plain = q["native"] if q["required"] else union([q["native"], "null"])
        if t not in ("mixed", plain):
            lines.append(f"@param {t} ${q['var']}")
    lines.append("@param RequestOptions $options")
    if paged:
        lines.append(f"@return \\Generator<int, {op['item']}, mixed, void>")
    elif op["result"]:
        lines.append(f"@return {op['result']}")
    return "    /**\n" + "\n".join(f"     * {line}".rstrip() for line in lines) + "\n     */\n"


def call(op, paged=False):
    parts = [f"'{op['http']}'", f"'{op['path']}'"] if not paged else [f"'{op['path']}'"]
    if op["path_params"]:
        parts.append("pathParams: [" + ", ".join(f"'{p}' => ${camel(p)}" for p in op["path_params"]) + "]")
    query = [
        f"'{q['name']}' => ${q['var']} ?? 'json'" if q["json_format"] else f"'{q['name']}' => ${q['var']}"
        for q in op["query"]
        if not (paged and q["name"] in PAGINATION_MANAGED)
    ]
    if query:
        parts.append("query: [" + ", ".join(query) + "]")
    if op["body"] and not paged:
        parts.append("body: $params")
        if op["list_body"]:
            parts.append("listBody: true")
    if op["idempotent"] and not paged:
        parts.append("idempotent: true")
        parts.append("idempotencyKey: $idempotencyKey")
    parts.append("options: $options")
    return f"$this->core->{'paginate' if paged else 'request'}(" + ", ".join(parts) + ")"


def type_names(t):
    """Alias names used in a PHPStan type."""
    stripped = re.sub(r"'(?:[^'\\]|\\.)*'", "", t)
    return {w for w in re.findall(r"\b[A-Z][A-Za-z0-9]*\b", stripped) if w in aliases}


tree = {"groups": {}, "ops": []}
for op in ops:
    node = tree
    for g in op["group"]:
        node = node["groups"].setdefault(g, {"groups": {}, "ops": []})
    node["ops"].append(op)

files = {}


def emit(node, prefix):
    cls = class_name(prefix)
    used = set()
    methods = []
    for op in node["ops"]:
        for t in [op["body"] or "", op["result"] or "", op["item"] or ""] + [q["doc"] for q in op["query"]]:
            used |= type_names(t)
        methods.append(
            docblock(op)
            + f"    public function {op['method']}({signature(op)}): mixed\n    {{\n        return {call(op)};\n    }}\n"
        )
        if op["item"]:
            methods.append(
                docblock(op, paged=True)
                + f"    public function {op['method']}All({signature(op, paged=True)}): \\Generator\n"
                + f"    {{\n        return {call(op, paged=True)};\n    }}\n"
            )
    children = [(g, class_name(prefix + [g])) for g in node["groups"]]
    head = ["/**"]
    head.append(f" * `$client->{'->'.join(prefix)}`" if prefix else " * The API groups of the client: `$client->emails`, `$client->domains` and the others.")
    if node["ops"]:
        head.append(" *")
        head += [f" * @phpstan-import-type {n} from Types" for n in sorted(used)]
        head.append(" * @phpstan-import-type RequestOptions from Core")
    head.append(" */")
    body = []
    for g, child in children:
        body.append(f"    public readonly {child} ${g};\n")
    ctor_core = "private readonly Core $core" if node["ops"] else "Core $core"
    inits = "".join(f"        $this->{g} = new {child}($core);\n" for g, child in children)
    body.append(f"    public function __construct({ctor_core})\n    {{\n{inits}    }}\n")
    body += methods
    kind = "abstract class" if not prefix else "final class"
    uses = ["use SMTPfast\\Core;"] + (["use SMTPfast\\Types;"] if used else [])
    files[cls] = (
        HEADER
        + "namespace SMTPfast\\Resources;\n\n"
        + "\n".join(uses)
        + "\n\n"
        + "\n".join(head)
        + f"\n{kind} {cls}\n{{\n"
        + "\n".join(body)
        + "}\n"
    )
    for g, child in node["groups"].items():
        emit(child, prefix + [g])


emit(tree, [])

types_doc = ["/**", " * Request and response shapes of the SMTPfast API, as PHPStan and Psalm array shapes.", " * At runtime they are plain arrays.", " *"]
for name, (t, description) in aliases.items():
    if description:
        types_doc.append(f" * {doc(description)}")
    types_doc.append(f" * @phpstan-type {name} {t}")
types_doc.append(" */")
types_src = HEADER + "namespace SMTPfast;\n\n" + "\n".join(types_doc) + "\nfinal class Types\n{\n}\n"

out_dir = ROOT / "src/Resources"
for old in out_dir.glob("*.php"):
    old.unlink()
for cls, src in files.items():
    (out_dir / f"{cls}.php").write_text(src)
(ROOT / "src/Types.php").write_text(types_src)
print(f"src/Types.php: {len(aliases)} types; src/Resources: {len(files)} classes, {len(ops)} operations")
